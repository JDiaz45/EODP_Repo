# Cross-validation
# ============================================================

def cross_validation():

    # Maximum allowed relative difference [%]
    limit = 1e-3

    lines = []

    header = (
        f"{'FILE':35s} "
        f"{'MAX ABS':>14s} "
        f"{'MAX REL %':>14s} "
        f"{'RESULT':>8s}"
    )

    separator = "-" * 76

    lines.append(header)
    lines.append(separator)

    overall = True

    # Compare every NetCDF generated by our L1B
    for my_file in sorted(MY_OUTPUT_DIR.glob("*.nc")):

        ref_file = REF_OUTPUT_DIR / my_file.name

        if not ref_file.exists():

            lines.append(
                f"{my_file.name:35s} "
                f"{'-':>14s} "
                f"{'-':>14s} "
                f"{'NO REF':>8s}"
            )

            overall = False
            continue

        # Read TOA arrays
        ref_toa = read_toa(ref_file)
        my_toa = read_toa(my_file)

        # Absolute difference
        diff = np.abs(my_toa - ref_toa)

        max_abs = np.max(diff)

        # Relative difference only where
        # the reference value is not zero
        mask = np.abs(ref_toa) > 1e-15

        if np.any(mask):

            relative_difference = (
                diff[mask]
                / np.abs(ref_toa[mask])
                * 100.0
            )

            max_rel = np.max(relative_difference)

        else:
            max_rel = 0.0

        passed = max_rel < limit

        overall &= passed

        lines.append(
            f"{my_file.name:35s} "
            f"{max_abs:14.6e} "
            f"{max_rel:14.6e} "
            f"{'PASS' if passed else 'FAIL':>8s}"
        )

    lines.append(separator)

    lines.append(
        f"OVERALL: {'PASS' if overall else 'FAIL'}"
    )

    lines.append(
        f"Required limit: {limit} %"
    )

    # Print report in terminal
    report = "\n".join(lines)

    print()
    print("L1B CROSS-VALIDATION")
    print()
    print(report)

    # Save report to file
    VALIDATION_REPORT.write_text(report)

    print()
    print(
        f"Validation report saved: "
        f"{VALIDATION_REPORT}"
    )

    return overall


