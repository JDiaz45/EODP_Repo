def read_toa(filepath):
    """
    Read the 'toa' variable from a NetCDF file.
    """
    with Dataset(filepath, "r") as dataset:
        return np.array(dataset.variables["toa"][:], dtype=float)


# ============================================================
# Plot: effect of equalization
# ============================================================

def plot_equalization():

    band = "VNIR-0"

    # Central ALT line
    alt_line = 50

    # Radiance after ISRF
    toa_isrf = read_toa(
        INPUT_DIR / f"ism_toa_isrf_{band}.nc"
    )

    # L1B input in DN
    toa_dn = read_toa(
        INPUT_DIR / f"ism_toa_{band}.nc"
    )

    # My final L1B result:
    # equalization + restoration
    toa_l1b_with_eq = read_toa(
        MY_OUTPUT_DIR / f"l1b_toa_{band}.nc"
    )

    # --------------------------------------------------------
    # L1B without equalization
    # --------------------------------------------------------

    config = l1bConfig()

    gain = config.gain[getIndexBand(band)]

    # Only restoration:
    # TOA_L1B = TOA_DN * Gain
    toa_l1b_no_eq = toa_dn * gain

    # ACT axis
    act = np.arange(toa_l1b_with_eq.shape[1])

    # --------------------------------------------------------
    # Plot
    # --------------------------------------------------------

    plt.figure(figsize=(10, 6))

    plt.plot(
        act,
        toa_l1b_with_eq[alt_line, :],
        label="TOA L1B with eq"
    )

    plt.plot(
        act,
        toa_l1b_no_eq[alt_line, :],
        label="TOA L1B no eq"
    )

    plt.plot(
        act,
        toa_isrf[alt_line, :],
        label="TOA after the ISRF"
    )

    plt.title(f"Effect of the Equalization for {band}")

    plt.xlabel("ACT pixel [-]")
    plt.ylabel("TOA [mW/m2/sr]")

    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    figure_path = FIGURES_DIR / f"equalization_{band}.png"

    plt.savefig(
        figure_path,
        dpi=200,
        bbox_inches="tight"
    )

    print(f"Figure saved: {figure_path}")

    plt.show()


